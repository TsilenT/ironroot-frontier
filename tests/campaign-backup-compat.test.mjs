test('each expanded mission exports, restores, re-exports and resumes on its declared battlefield', () => {
  for (const mission of expandedMissions()) {
    const game = createCampaignMission(mission.id); game.update(.023);
    const battle = envelope(game, mission.id), history = [historyRow(mission)];
    const text = createBackup(storage(), { createdAt: date, campaign: fullProgress(), battle, history });
    const parsed = parseBackup(text); assert.deepEqual(parsed.data.battle, battle); assert.deepEqual(parsed.data.history, history);
    const r = storage(), p = session(r); assert.equal(p.beginImport().ok, true);
    assert.equal(restoreBackup(p.importStorage, text).ok, true); assert.equal(p.finishImport({ outcome: 'restored' }).ok, true);
    assert.equal(createBackup(session(r).storage, { createdAt: date }), text);
    const restored = Game.restore(JSON.parse(r.data.get(K.battle)).game);
    assert.equal(restored.map.id, mission.mapId); assert.deepEqual(restored.serialize(), game.serialize());
    for (let i = 0; i < 700; i++) { const dt = [.017, .023, .05, .071, .009, .13][i % 6]; game.update(dt); restored.update(dt); }
    assert.deepEqual(restored.serialize(), game.serialize(), `${mission.id}: deterministic continuation`);
  }
});

