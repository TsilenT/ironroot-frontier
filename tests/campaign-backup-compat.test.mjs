const clone = value => JSON.parse(JSON.stringify(value));
const digest = value => createHash('sha256').update(value).digest('hex');
const envelope = (game, campaignId = null, challengeId = null) => ({ format: 'ironroot-save', version: 2, challengeId, campaignId, game: game.serialize() });
