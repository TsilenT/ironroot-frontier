function storage(entries = []) {
  const data = new Map(entries), operations = [];
  return { data, operations,
    getItem(key) { operations.push(['get', key]); return data.has(key) ? data.get(key) : null; },
    setItem(key, value) { operations.push(['set', key, value]); data.set(key, value); },
    removeItem(key) { operations.push(['remove', key]); data.delete(key); },
  };
}
function fullProgress() {
  const progress = createCampaignProgress();
  for (const mission of CAMPAIGN_MISSIONS) progress.missions[mission.id] = { completed: true, stars: 3, bestTime: 60 };
  return progress;
}
function fixture(missionId = missionIds[0]) {
  const mission = CAMPAIGN_MISSIONS.find(m => m.id === missionId);
  return JSON.parse(createBackup(storage(), { createdAt: date, campaign: fullProgress(), history: [historyRow(mission)], battle: envelope(createCampaignMission(mission.id), mission.id) }));
}
function invalid(value, pattern = BackupError) {
  const beforeInput = JSON.stringify(value), text = beforeInput;
  assert.throws(() => parseBackup(text), pattern);
  const s = storage(keys.map((key, i) => [key, ` original bytes ${i}\n`])), before = [...s.data];
  const result = restoreBackup(s, text);
  assert.equal(result.ok, false); assert.equal(result.rollback.attempted, false);
  assert.deepEqual(s.operations, [], 'reject malformed backups before destination access');
  assert.deepEqual([...s.data], before); assert.equal(JSON.stringify(value), beforeInput);
}
