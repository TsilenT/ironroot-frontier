test('new-map campaign restoration retains verified rollback at every domain write failure', () => {
  const incoming = JSON.stringify(fixture('common-ground'));
  for (const failedKey of keys) {
    const r = storage(keys.map((key, i) => [key, ` original ${i} `])), p = session(r), before = keys.map(key => [key, r.data.get(key)]);
    assert.equal(p.beginImport().ok, true); const set = r.setItem.bind(r); let failed = false;
    r.setItem = (key, value) => { if (key === failedKey && !failed) { failed = true; throw Error('quota'); } set(key, value); };
    const result = restoreBackup(p.importStorage, incoming);
    assert.equal(result.ok, false); assert.equal(result.rollback.complete, true); assert.equal(result.code, 'write-failed-rolled-back');
    assert.deepEqual(keys.map(key => [key, r.data.get(key)]), before);
    const finalized = p.finishImport({ outcome: 'rolled-back' }); assert.equal(finalized.ok, true); assert.equal(finalized.status.canWrite, true);
    assert.equal(JSON.parse(r.data.get(KEY)).version, 2);
  }
});
