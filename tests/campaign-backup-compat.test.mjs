test('legacy v0.7-format and v0.9 backups retain exact canonical bytes and all twelve campaign records', () => {
  for (const [name, sha, mapId] of legacyFixtures) {
    const text = readFileSync(new URL(`./fixtures/${name}`, import.meta.url), 'utf8');
    assert.equal(digest(text), sha);
    const parsed = parseBackup(text), original = JSON.parse(text);
    assert.deepEqual(parsed, original); assert.equal(Object.keys(parsed.data.campaign.missions).length, 12);
    assert.equal(Game.restore(parsed.data.battle.game).map.id, mapId);
    assert.equal(parsed.data.history[0].mapId, undefined);
    const r = storage([['unrelated.secret', 'private']]), p = session(r);
    assert.equal(p.beginImport().ok, true); assert.equal(restoreBackup(p.importStorage, text).ok, true);
    assert.equal(p.finishImport({ outcome: 'restored' }).ok, true);
    const reloaded = session(r), exported = createBackup(reloaded.storage, { createdAt: date });
    assert.equal(exported, text); assert.equal(r.data.get('unrelated.secret'), 'private');
    assert.equal(JSON.parse(r.data.get(KEY)).version, 2);
    const overview = getCampaignOverview(parsed.data.campaign);
    assert.equal(overview.cleared, 12); assert.equal(overview.stars, 36); assert.equal(overview.total, 16); assert.equal(overview.maxStars, 48);
    assert.equal(overview.nextMissionId, 'open-horizon'); assert.equal(overview.completed, false);
  }
});

