test('all three maps create, parse, restore, re-export and retain unchanged versioned wrappers', () => {
  assert.equal(BACKUP_VERSION, 1);
  for (const mapId of mapIds) {
    const game = new Game({ mapId, seed: 91 }), battle = envelope(game);
    const source = storage([[K.battle, JSON.stringify(battle)]]), raw = [...source.data];
    const text = createBackup(source, { createdAt: date }), parsed = parseBackup(text);
    assert.equal(parsed.version, 1); assert.equal(parsed.data.battle.version, 2);
    assert.deepEqual(parsed.data.battle, battle);
    assert.equal(parsed.data.battle.game.version, mapId === 'classic' ? 1 : 2);
    const restored = storage([['unrelated.secret', 'untouched']]);
    assert.equal(restoreBackup(restored, text).ok, true);
    assert.equal(createBackup(restored, { createdAt: date }), text);
    assert.equal(restored.data.get('unrelated.secret'), 'untouched');
    const copy = Game.restore(JSON.parse(restored.data.get(K.battle)).game);
    assert.equal(copy.map.id, mapId); assert.equal(copy.map.revision, 1);
    assert.deepEqual(copy.serialize(), game.serialize());
    assert.deepEqual([...source.data], raw);
    assert.ok(source.operations.every(([op]) => op === 'get'));
    restored.operations.length = 0;
    assert.deepEqual(restoreBackup(restored, text).changedKeys, []);
    assert.ok(restored.operations.every(([op]) => op === 'get'));
  }
});

