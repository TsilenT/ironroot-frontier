function storage(entries = []) {
  const data = new Map(entries), operations = [];
  return { data, operations,
    getItem(key) { operations.push(['get', key]); return data.has(key) ? data.get(key) : null; },
    setItem(key, value) { operations.push(['set', key, value]); data.set(key, value); },
    removeItem(key) { operations.push(['remove', key]); data.delete(key); },
  };
}
function fixture(mapId = 'classic') {
  return JSON.parse(createBackup(storage(), { battle: envelope(new Game({ mapId })), createdAt: date }));
}
function invalid(value, pattern = BackupError, engineInvalid = false) {
  const text = JSON.stringify(value), beforeInput = clone(value);
  assert.throws(() => parseBackup(text), pattern);
  const s = storage(keys.map((key, i) => [key, ` original corrupt ${i}\n`])), before = [...s.data];
  const result = restoreBackup(s, text);
  assert.equal(result.ok, false);
  assert.equal(result.code, 'invalid-backup');
  assert.deepEqual(s.operations, [], 'invalid data must fail before storage access');
  assert.deepEqual([...s.data], before);
  assert.equal(result.rollback.attempted, false);
  assert.deepEqual(value, beforeInput);
  if (engineInvalid) assert.throws(() => Game.restore(value.data.battle.game));
}
function freeze(value) {
  if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); }
  return value;
}
function fullProgress() {
  const progress = createCampaignProgress();
  for (const mission of CAMPAIGN_MISSIONS) progress.missions[mission.id] = { completed: true, stars: 2, bestTime: 60 };
  return progress;
}
function combat(mapId) {
  const game = new Game({ mapId, ai: false, seed: 927 });
  game.state.gold = [10000, 10000];
  for (const side of [0, 1]) for (const [type, home, lane] of [['barracks',1250,0], ['archery',1110,0], ['aerie',1250,game.map.lanes.length-1]])
    assert.equal(game.build(type, side ? game.map.width - home : home, game.map.lanes[lane], side).ok, true);
  for (let i = 0; i < 1000; i++) game.update(.05);
  for (let i = 0; i < 600 && game.state.projectiles.length === 0; i++) game.update(.05);
  assert.ok(game.state.projectiles.length > 0, 'checkpoint contains live projectiles');
  game.update(.023);
  assert.equal(game.state.winner, null);
  assert.ok(game.accumulator > 0 && game.accumulator < .05);
  return game;
}

