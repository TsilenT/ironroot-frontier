test('new-map imports preserve quota rollback semantics at all five write positions', () => {
  for (const mapId of mapIds.slice(1)) {
    const value = fixture(mapId); value.data.history = [row({ mapId })]; const text = JSON.stringify(value);
    for (let failAt = 1; failAt <= keys.length; failAt++) {
      const originals = keys.map((key, i) => [key, `  corrupt old ${i}\n`]), s = storage(originals);
      let count = 0; s.setItem = (key, bytes) => { if (++count === failAt) throw Error('QuotaExceededError'); s.data.set(key, bytes); };
      const result = restoreBackup(s, text);
      assert.equal(result.ok, false); assert.equal(result.code, 'write-failed-rolled-back');
      assert.equal(result.failedKey, keys[failAt - 1]); assert.equal(result.rollback.complete, true);
      assert.deepEqual([...s.data], originals); assert.deepEqual(result.changedKeys, []);
    }
  }
});

test('new-map profile imports retain stale-tab barriers and exact-outcome finalization retry', () => {
  for (const mapId of mapIds.slice(1)) {
    const s = storage(), importer = createProfileSession(() => s, { newEpoch: () => 'map-import' }), stale = createProfileSession(() => s);
    assert.equal(importer.beginImport().ok, true);
    assert.equal(restoreBackup(importer.importStorage, JSON.stringify(fixture(mapId))).ok, true);
    const battleBytes = s.data.get(K.battle), originalSet = s.setItem;
    s.setItem = (key, bytes) => { if (key === PROFILE_MARKER_KEY) throw Error('QuotaExceededError'); originalSet(key, bytes); };
    const pending = importer.finishImport({ outcome: 'restored' });
    assert.equal(pending.ok, false); assert.equal(pending.status.canReload, false); assert.equal(pending.status.canWrite, false);
    assert.equal(importer.finishImport({ outcome: 'rolled-back' }).code, 'outcome-conflict');
    assert.equal(s.data.get(K.battle), battleBytes);
    for (const session of [importer, stale]) for (const key of keys) assert.throws(() => session.storage.setItem(key, 'stale'));
    s.setItem = originalSet;
    assert.equal(importer.finishImport({ outcome: 'restored' }).ok, true);
    assert.equal(importer.status().reloadRequired, true); assert.equal(stale.status().reloadRequired, true);
    const reloaded = createProfileSession(() => s);
    assert.equal(reloaded.status().canWrite, true);
    assert.equal(Game.restore(JSON.parse(reloaded.storage.getItem(K.battle)).game).map.id, mapId);
    assert.equal(s.data.get(K.battle), battleBytes);
  }
});

